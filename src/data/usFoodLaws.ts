/**
 * US federal and state rules on food additives, from a verified web research
 * (docs/research/us-food-laws). They are shown on each additive, not counted:
 * for food the EU's list of authorised additives is the reference, and every
 * additive a US rule names is either authorised there (with its conditions)
 * or already penalised as not authorised. The FDA's own positions that weigh
 * are in the cited evidence (src/data/evidence.ts).
 */

export type UsLawKind =
  | "federal-ban"
  | "state-ban"
  | "school-ban"
  | "warning-label"
  | "federal-plan";

export interface UsLaw {
  jurisdiction: string;
  kind: UsLawKind;
  law: string;
  /** ISO date the rule applies from, when the text sets one. */
  effective?: string;
  summary: { en: string; fr: string; de: string };
  source: { org: string; year: number; title: string; url: string };
}

/** Where the school-meal bans are cited one by one. */
export const US_FOOD_LAWS_RESEARCH =
  "https://github.com/maxgfr/goodscan/tree/main/docs/research/us-food-laws";

/**
 * The rules to show: each federal rule, statewide ban and warning label, then
 * the school-meal bans as one line (a dozen states name the same dyes).
 */
export function lawsShown(laws: readonly UsLaw[]): Omit<UsLaw, "law" | "kind">[] {
  const school = laws.filter((l) => l.kind === "school-ban");
  const rest = laws.filter((l) => l.kind !== "school-ban");
  if (!school.length) return rest;
  const states = [...new Set(school.map((l) => l.jurisdiction))].sort();
  const n = states.length;
  const list = states.join(", ");
  return [
    ...rest,
    {
      jurisdiction: "US states",
      summary:
        n === 1
          ? {
              en: `Banned in school meals in ${list}.`,
              fr: `Interdit dans les repas scolaires (${list}).`,
              de: `In Schulmahlzeiten verboten (${list}).`,
            }
          : {
              en: `Banned in school meals in ${n} US states: ${list}.`,
              fr: `Interdit dans les repas scolaires de ${n} États américains : ${list}.`,
              de: `In Schulmahlzeiten von ${n} US-Bundesstaaten verboten: ${list}.`,
            },
      source: {
        org: "goodscan research",
        year: Math.max(...school.map((l) => l.source.year)),
        title: "US federal and state food additive laws",
        url: US_FOOD_LAWS_RESEARCH,
      },
    },
  ];
}

